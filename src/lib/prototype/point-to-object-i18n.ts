export const pointObjectCopy = { en, ru } as const;
export type PointObjectCopyKey = CopyKey;

export function normalizePointObjectLocale(value: unknown): PointObjectLocale {
  return value === "ru" ? "ru" : "en";
}

export function interpolatePointObjectCopy(
  value: string,
  parameters: Record<string, string | number> = {}
): string {
  return value.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(parameters, key) ? String(parameters[key]) : match
  );
}
